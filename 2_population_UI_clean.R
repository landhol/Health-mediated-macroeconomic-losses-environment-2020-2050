# ------------------------------------------------------------------------------
# 6. Helper function for matrix extraction
# ------------------------------------------------------------------------------

data_matrix <- function(data, a, t, measure) {
  data_sel <- data %>%
    subset(age == a & year == t) %>%
    select(c("cause_name", "WBcode", measure))

  return(data_sel)
}


# ------------------------------------------------------------------------------
# 7. Calculate disease-specific counterfactual population
# ------------------------------------------------------------------------------

calculate_N <- function(data, s) {

  data_m <- data %>%
    subset(sex == s) %>%
    mutate(
      D_val = 1 - val,
      D_lower = 1 - lower,
      D_upper = 1 - upper
    )

  Nt_ca <- as.data.frame(matrix(nrow = 0, ncol = 7))

  total_iterations <- n_distinct(data$age) * n_distinct(data$year)

  pb <- progress_bar$new(
    format = "Calculating [:bar] :percent | :current/:total | eta: :eta",
    total = total_iterations,
    width = 60
  )

  for (a in 1:n_distinct(data$age)) {

    Nt_ct <- as.data.frame(matrix(nrow = 0, ncol = 6))

    for (t in 1:n_distinct(data$year)) {

      pb$tick()

      # The matrix dimensions depend on the number of countries and diseases
      # in the current analysis (204 countries and 55 columns here).
      result_val <- as.data.frame(matrix(1, nrow = 204, ncol = 55))
      result_lower <- as.data.frame(matrix(1, nrow = 204, ncol = 55))
      result_upper <- as.data.frame(matrix(1, nrow = 204, ncol = 55))

      data_N <- data_matrix(
        data_m,
        age_name[a],
        year_name[t],
        "number"
      )

      N_matrix <- spread(
        data_N,
        key = cause_name,
        value = number
      )

      N_matrix <- select(N_matrix, c(2:56))

      if (min(a, t) == 1 | t < 6) {

        result_val <- N_matrix
        result_lower <- N_matrix
        result_upper <- N_matrix

      } else {

        for (i in 0:(min(a, floor((t + 4) / 5)) - 2)) {

          # Point estimate: calculate cumulative survival probabilities over the
          # relevant preceding 5-year periods.
          data_D1 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 5 - 5 * i], "D_val"
          )
          data_D2 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 4 - 5 * i], "D_val"
          )
          data_D3 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 3 - 5 * i], "D_val"
          )
          data_D4 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 2 - 5 * i], "D_val"
          )
          data_D5 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 1 - 5 * i], "D_val"
          )

          D1_matrix <- spread(data_D1, key = cause_name, value = D_val)
          D1_matrix <- select(D1_matrix, c(2:56))
          D2_matrix <- spread(data_D2, key = cause_name, value = D_val)
          D2_matrix <- select(D2_matrix, c(2:56))
          D3_matrix <- spread(data_D3, key = cause_name, value = D_val)
          D3_matrix <- select(D3_matrix, c(2:56))
          D4_matrix <- spread(data_D4, key = cause_name, value = D_val)
          D4_matrix <- select(D4_matrix, c(2:56))
          D5_matrix <- spread(data_D5, key = cause_name, value = D_val)
          D5_matrix <- select(D5_matrix, c(2:56))

          result_val <- (
            result_val *
            D1_matrix *
            D2_matrix *
            D3_matrix *
            D4_matrix *
            D5_matrix
          )

          # Lower GBD epidemiological bound.
          data_D1 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 5 - 5 * i], "D_lower"
          )
          data_D2 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 4 - 5 * i], "D_lower"
          )
          data_D3 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 3 - 5 * i], "D_lower"
          )
          data_D4 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 2 - 5 * i], "D_lower"
          )
          data_D5 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 1 - 5 * i], "D_lower"
          )

          D1_matrix <- spread(data_D1, key = cause_name, value = D_lower)
          D1_matrix <- select(D1_matrix, c(2:56))
          D2_matrix <- spread(data_D2, key = cause_name, value = D_lower)
          D2_matrix <- select(D2_matrix, c(2:56))
          D3_matrix <- spread(data_D3, key = cause_name, value = D_lower)
          D3_matrix <- select(D3_matrix, c(2:56))
          D4_matrix <- spread(data_D4, key = cause_name, value = D_lower)
          D4_matrix <- select(D4_matrix, c(2:56))
          D5_matrix <- spread(data_D5, key = cause_name, value = D_lower)
          D5_matrix <- select(D5_matrix, c(2:56))

          result_lower <- (
            result_lower *
            D1_matrix *
            D2_matrix *
            D3_matrix *
            D4_matrix *
            D5_matrix
          )

          # Upper GBD epidemiological bound.
          data_D1 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 5 - 5 * i], "D_upper"
          )
          data_D2 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 4 - 5 * i], "D_upper"
          )
          data_D3 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 3 - 5 * i], "D_upper"
          )
          data_D4 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 2 - 5 * i], "D_upper"
          )
          data_D5 <- data_matrix(
            data_m, age_name[a - 1 - i], year_name[t - 1 - 5 * i], "D_upper"
          )

          D1_matrix <- spread(data_D1, key = cause_name, value = D_upper)
          D1_matrix <- select(D1_matrix, c(2:56))
          D2_matrix <- spread(data_D2, key = cause_name, value = D_upper)
          D2_matrix <- select(D2_matrix, c(2:56))
          D3_matrix <- spread(data_D3, key = cause_name, value = D_upper)
          D3_matrix <- select(D3_matrix, c(2:56))
          D4_matrix <- spread(data_D4, key = cause_name, value = D_upper)
          D4_matrix <- select(D4_matrix, c(2:56))
          D5_matrix <- spread(data_D5, key = cause_name, value = D_upper)
          D5_matrix <- select(D5_matrix, c(2:56))

          result_upper <- (
            result_upper *
            D1_matrix *
            D2_matrix *
            D3_matrix *
            D4_matrix *
            D5_matrix
          )
        }

        # Counterfactual population equals the status quo population divided by
        # the cumulative survival probability associated with disease-specific
        # mortality.
        result_val <- N_matrix / result_val
        result_lower <- N_matrix / result_lower
        result_upper <- N_matrix / result_upper
      }

      result_val$WBcode <- country_code
      result_lower$WBcode <- country_code
      result_upper$WBcode <- country_code

      # Convert matrices back to long format.
      result_val_data <- gather(
        data = as.data.frame(result_val),
        key = "cause_name",
        value = "N_val",
        -WBcode
      )

      result_lower_data <- gather(
        data = as.data.frame(result_lower),
        key = "cause_name",
        value = "N_lower",
        -WBcode
      )

      result_upper_data <- gather(
        data = as.data.frame(result_upper),
        key = "cause_name",
        value = "N_upper",
        -WBcode
      )

      result_data <- result_val_data %>%
        merge(
          result_lower_data,
          by = c("cause_name", "WBcode")
        )

      result_data <- result_data %>%
        merge(
          result_upper_data,
          by = c("cause_name", "WBcode")
        )

      result_data$year <- year_name[t]
      Nt_ct <- rbind(Nt_ct, result_data)
    }

    Nt_ct$age <- age_name[a]
    Nt_ca <- rbind(Nt_ca, Nt_ct)
  }

  Nt_ca$sex <- s

  return(Nt_ca)
}


