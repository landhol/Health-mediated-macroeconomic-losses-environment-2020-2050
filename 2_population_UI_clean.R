# ------------------------------------------------------------------------------
# 8. Aggregate ages 65+ and retain working-age groups
# ------------------------------------------------------------------------------

combine_N <- function(data) {

  # Aggregate all age groups 65+ into a single 65+ category.
  filtered_data <- data %>%
    filter(
      age %in% c(
        "65-69", "70-74", "75-79", "80-84",
        "85-89", "90-94", "95+"
      )
    ) %>%
    arrange(cause_name, WBcode, sex, year, age) %>%
    group_by(cause_name, WBcode, sex, year) %>%
    mutate(
      N_val = sum(N_val),
      N_lower = sum(N_lower),
      N_upper = sum(N_upper),
      age = "65+"
    ) %>%
    distinct(
      cause_name,
      WBcode,
      year,
      sex,
      .keep_all = TRUE
    )

  # Remove the original 65+ age groups and populations younger than 15 years.
  data_new <- data %>%
    filter(
      !(
        age %in% c(
          "0-4", "5-9", "10-14",
          "65-69", "70-74", "75-79", "80-84",
          "85-89", "90-94", "95+"
        )
      )
    )

  data_final <- data_new %>%
    bind_rows(filtered_data) %>%
    arrange(cause_name, WBcode, sex, year, age)

  return(data_final)
}

